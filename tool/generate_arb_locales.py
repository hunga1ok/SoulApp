def main():
    en_data = json.loads(EN_ARB_PATH.read_text(encoding="utf-8"))
    for lang, trans in TRANSLATIONS.items():
        out = {}
        for k, v in en_data.items():
            if k.startswith("@"):
                if k == "@@locale":
                    out[k] = lang
                else:
                    # Keep metadata blocks identical to template
                    out[k] = v
            else:
                if k not in trans:
                    raise KeyError(f"Missing key '{k}' in {lang} translation")
                out[k] = trans[k]
        out_path = ROOT / "lib" / "l10n" / f"app_{lang}.arb"
        out_path.write_text(
            json.dumps(out, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"Wrote {out_path} ({len(out)} entries)")


if __name__ == "__main__":
    main()
